from enum import Enum
from typing import List, Optional, Dict, Any
from pydantic import BaseModel, Field


class ItemCategory(str, Enum):
    TSHIRT = "t-shirt"
    JEANS = "jeans"
    JACKET = "jacket"
    SHOES = "shoes"
    DRESS = "dress"
    SWEATER = "sweater"
    HOODIE = "hoodie"
    SHORTS = "shorts"
    SKIRT = "skirt"
    PANTS = "pants"
    COAT = "coat"
    SHIRT = "shirt"
    ACCESSORIES = "accessories"
    OTHER = "other"


class MaterialType(str, Enum):
    ORGANIC_COTTON = "organic_cotton"
    CONVENTIONAL_COTTON = "conventional_cotton"
    RECYCLED_POLYESTER = "recycled_polyester"
    VIRGIN_POLYESTER = "virgin_polyester"
    DENIM = "denim"
    WOOL = "wool"
    LINEN = "linen"
    LEATHER = "leather"
    SILK = "silk"
    SYNTHETIC_BLEND = "synthetic_blend"
    UNKNOWN = "unknown"


class GarmentCondition(str, Enum):
    NEW_FAST_FASHION = "new_fast_fashion"
    NEW_STANDARD = "new_standard"
    SUSTAINABLE_BRAND = "sustainable_brand"
    SECOND_HAND = "second_hand"
    VINTAGE = "vintage"
    UPCYCLED_REPAIRED = "upcycled_repaired"


class DetectedItem(BaseModel):
    id: str = Field(..., description="Unique identifier for the detected item")
    name: str = Field(..., description="Human readable item description, e.g. Vintage Blue Denim Jeans")
    category: ItemCategory = Field(default=ItemCategory.OTHER)
    color: Optional[str] = Field(default=None, description="Primary color of the garment")
    material: MaterialType = Field(default=MaterialType.UNKNOWN)
    condition: GarmentCondition = Field(default=GarmentCondition.NEW_STANDARD)
    confidence: float = Field(default=0.85, ge=0.0, le=1.0, description="Detection confidence score")
    sustainability_tip: Optional[str] = Field(default=None, description="Actionable tip to extend garment lifecycle")


class ScoredClothingItem(BaseModel):
    item: DetectedItem
    baseline_co2_kg: float = Field(..., description="Standard industry benchmark footprint for category")
    material_multiplier: float = Field(..., description="Multiplier based on fiber and textile type")
    condition_multiplier: float = Field(..., description="Multiplier reflecting reuse/repair savings")
    estimated_co2_kg: float = Field(..., description="Net estimated carbon footprint in kg CO2e")
    eco_savings_kg: float = Field(..., description="CO2e avoided relative to standard new item")
    item_reward_points: int = Field(..., description="Eco-reward points generated by this item")


class EnvironmentalEquivalencies(BaseModel):
    car_km_avoided: float = Field(..., description="Equivalent kilometers in average petrol car")
    smartphone_charges: int = Field(..., description="Equivalent smartphone full recharges")
    trees_days_absorption: float = Field(..., description="Tree carbon absorption days equivalent")


class ScanResponse(BaseModel):
    scan_id: str
    timestamp: str
    vision_source: str = Field(..., description="azure_gpt4_vision or mock_vision_heuristic")
    items: List[ScoredClothingItem]
    total_carbon_kg: float
    total_baseline_kg: float
    total_savings_kg: float
    total_reward_points: int
    equivalencies: EnvironmentalEquivalencies
    sustainability_summary: str
